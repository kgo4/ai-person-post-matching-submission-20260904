UPDATE learning_resource
SET title = CONVERT(CAST(CONVERT(title USING latin1) AS BINARY) USING utf8mb4),
    description = CASE WHEN description IS NULL THEN NULL
        ELSE CONVERT(CAST(CONVERT(description USING latin1) AS BINARY) USING utf8mb4) END
WHERE HEX(title) REGEXP 'C3A5C2|C3A6C2|C3A7C2|C3A8C2|C3A9C2|C3AF'
   OR HEX(description) REGEXP 'C3A5C2|C3A6C2|C3A7C2|C3A8C2|C3A9C2|C3AF';
