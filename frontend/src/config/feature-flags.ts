/**
 * 前端功能开关。
 *
 * 为什么需要它：
 * 有些功能主系统侧已经建好，但对端（或上下游某一环）尚未实现，此时**功能入口必须隐藏**，
 * 而不是让用户点进去拿到空列表或报错——「看起来能用但一用就废」比「没有这个入口」更伤信任。
 *
 * 约定：
 * - 开关名用 `<域>_<能力>_ENABLED`，默认值即当前对外口径；
 * - 隐藏入口时**保留实现代码**（用 v-if 包住），对端就绪后把开关置 true 即可恢复，
 *   不需要重新开发、也不需要在一堆文件里找回被删掉的分支；
 * - 每个开关都要写清「为什么关」与「什么条件下可以开」，否则下一个人不知道能不能动它。
 */

