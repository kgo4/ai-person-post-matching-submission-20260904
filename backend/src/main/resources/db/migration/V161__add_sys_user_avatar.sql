-- =============================================================================
-- V161：sys_user 增加头像列，支撑「个人中心」自助维护资料
--
-- 背景：顶栏右上角账号入口要能进入「个人中心」修改头像/手机号/邮箱。
--   手机号(phone)、邮箱(email) 列早已存在，只缺口像列。
--
-- 关键口径：
--   · 只加列，不改任何既有列与数据；
--   · 头像存**访问路径**（如 /uploads/avatars/xxx.png），不存二进制 ——
--     与学习资源封面上传保持同一存储方式（本地 uploads 目录 + /uploads/** 静态映射），
--     避免把大字段塞进账号表、也便于将来换成对象存储时只改上传实现。
-- =============================================================================

ALTER TABLE sys_user
    ADD COLUMN avatar VARCHAR(500) NULL COMMENT '头像访问路径（如 /uploads/avatars/xxx.png）' AFTER email;
